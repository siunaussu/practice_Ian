class Calculator:
    def add_number(self, a: int, b: int) -> int:
        """
            Add two numbers
        :param a:
        :param b:
        :return:
        """
        return a + b

    def minus_number(self, a: int, b: int) -> int:
        """
            minus two numbers
        :param a:
        :param b:
        :return:
        """
        return a - b

    def multi_number(self, a: int, b: int) -> int:
        """
            multi two numbers
        :param a:
        :param b:
        :return:
        """
        return a * b

    def divi_number(self, a: int, b: int) -> float:
        """
            divi two numbers
        :param a:
        :param b:
        :return:
        """
        return  a / b
